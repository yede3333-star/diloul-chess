#!/usr/bin/env node
/**
 * Generates src/styles/piece-glyphs.css from Chessground's cburnett piece set,
 * so move text can show the same piece drawings as the board (SPEC §17.4).
 * Inline glyphs always use the white (outlined) drawing: it reads on dark and light backgrounds.
 * Run again only if the chessground version changes: node scripts/gen-piece-glyphs.mjs
 */
import { readFile, writeFile } from "node:fs/promises";

const src = await readFile(new URL("../node_modules/chessground/assets/chessground.cburnett.css", import.meta.url), "utf8");
const roles = { K: "king", Q: "queen", R: "rook", B: "bishop", N: "knight" };
let out = `/* Generated by scripts/gen-piece-glyphs.mjs from chessground/assets/chessground.cburnett.css.
   cburnett pieces by Colin M.L. Burnett, licensed GPLv2+. Do not edit by hand. */\n`;
for (const [letter, role] of Object.entries(roles)) {
  const m = src.match(new RegExp(`piece\\.${role}\\.white\\s*\\{\\s*background-image:\\s*(url\\('[^']+'\\))`));
  if (!m) throw new Error(`cburnett ${role} not found`);
  out += `.san-piece[data-p="${letter}"]{background-image:${m[1]}}\n`;
}
await writeFile(new URL("../src/styles/piece-glyphs.css", import.meta.url), out);
console.log("Wrote src/styles/piece-glyphs.css");
